#!/usr/bin/env node
/* dev/cli-trooper-build.cjs <frames-dir> — pack the trooper's pixel-art frames into bin/lib/trooper-art.js (the CLI ships no
   image library, so the frames go in as one palette and deflated palette indexes).

   The frames are PixelLab pixel art, 128 × 80, transparent background: an armored trooper at its desk.
     work-0.png … work-8.png   typing (work-0 is also the still the other states recolour)
     idle-6.png, idle-5.png    powered down: all dark, and the flicker of a dim visor (the stopped state)
   Sources: create_image_pro job 255674a7 (candidate 3), animate_image jobs a8a54f18 (typing) and 1a6e2bf0 (power-down). */
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const sharp = require('sharp');

const dir = process.argv[2];
if (!dir) { console.error('usage: node dev/cli-trooper-build.cjs <frames-dir>'); process.exit(2); }
const OUT = path.join(__dirname, '..', 'bin', 'lib', 'trooper-art.js');
const SETS = { working: [0, 1, 2, 3, 4, 5, 6, 7, 8].map(i => 'work-' + i + '.png'), stopped: ['idle-6.png', 'idle-5.png'] };

(async () => {
  const palette = [], index = new Map();
  const frames = {};
  let W = 0, H = 0;
  for (const [set, files] of Object.entries(SETS)) {
    frames[set] = [];
    for (const f of files) {
      const { data, info } = await sharp(path.join(dir, f)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
      if (W && (info.width !== W || info.height !== H)) throw new Error(f + ' is ' + info.width + 'x' + info.height + ', not ' + W + 'x' + H);
      W = info.width; H = info.height;
      const px = Buffer.alloc(W * H, 255);   // 255 = no pixel
      for (let i = 0; i < W * H; i++) {
        if (data[i * 4 + 3] < 128) continue;
        const k = data[i * 4] + ',' + data[i * 4 + 1] + ',' + data[i * 4 + 2];
        if (!index.has(k)) { if (palette.length >= 255) throw new Error('more than 255 colours'); index.set(k, palette.length); palette.push(k.split(',').map(Number)); }
        px[i] = index.get(k);
      }
      frames[set].push(zlib.deflateSync(px, { level: 9 }).toString('base64'));
    }
  }
  const src = "/* bin/lib/trooper-art.js — GENERATED by dev/cli-trooper-build.cjs: the trooper's pixel-art frames (" + W + ' x ' + H + ', ' + palette.length + ' colours).\n' +
    '   Each frame is deflated palette indexes, one byte a pixel, row by row; 255 = no pixel. Do not edit by hand. */\n' +
    "'use strict';\n" +
    'module.exports = {\n' +
    '  width: ' + W + ',\n  height: ' + H + ',\n' +
    '  palette: ' + JSON.stringify(palette) + ',\n' +
    '  frames: {\n' + Object.entries(frames).map(([k, v]) => '    ' + k + ': [\n' + v.map(b => "      '" + b + "'").join(',\n') + '\n    ]').join(',\n') + '\n  }\n};\n';
  fs.writeFileSync(OUT, src);
  console.log('wrote', path.relative(process.cwd(), OUT), (src.length / 1024).toFixed(1) + ' KB', palette.length, 'colours', Object.entries(frames).map(([k, v]) => k + ' ' + v.length).join(', '));
})().catch(e => { console.error(e.message || e); process.exit(1); });
