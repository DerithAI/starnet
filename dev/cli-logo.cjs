'use strict';
/* node dev/cli-logo.cjs [--write] — the terminal's StarNet logo, in characters:
   • the STAR is cut from src-tauri/icon-source.png (the master every StarNet icon is cut from — never redrawn): its
     orange phosphor masked, trimmed and set in half blocks (▀ ▄ █), 13×6 cells;
   • the WORDMARK is STARNET in shadowed block letters (█ with ╗ ║ ╝ shadows), each row stepped one cell to the right
     going up so it leans forward like the brand wordmark.
   Prints the logo; --write regenerates bin/lib/logo.js. Needs the dev dependency sharp. */
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');

const REPO = path.resolve(__dirname, '..');
const STAR = path.join(REPO, 'src-tauri', 'icon-source.png');

const FONT = {
  S: ['███████╗', '██╔════╝', '███████╗', '╚════██║', '███████║', '╚══════╝'],
  T: ['████████╗', '╚══██╔══╝', '   ██║   ', '   ██║   ', '   ██║   ', '   ╚═╝   '],
  A: [' █████╗ ', '██╔══██╗', '███████║', '██╔══██║', '██║  ██║', '╚═╝  ╚═╝'],
  R: ['██████╗ ', '██╔══██╗', '██████╔╝', '██╔══██╗', '██║  ██║', '╚═╝  ╚═╝'],
  N: ['███╗   ██╗', '████╗  ██║', '██╔██╗ ██║', '██║╚██╗██║', '██║ ╚████║', '╚═╝  ╚═══╝'],
  E: ['███████╗', '██╔════╝', '█████╗  ', '██╔══╝  ', '███████╗', '╚══════╝']
};
function wordmark(text) {
  const rows = FONT.S.length;
  return Array.from({ length: rows }, (_, r) => ' '.repeat(rows - 1 - r) + text.split('').map(ch => FONT[ch][r]).join('')).map(l => l.replace(/\s+$/, ''));
}

async function star(cols, rows, threshold) {
  const { data, info } = await sharp(STAR).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const W = info.width, H = info.height, m = new Uint8Array(W * H);
  for (let i = 0; i < W * H; i++) { const r = data[i * 4], b = data[i * 4 + 2], a = data[i * 4 + 3]; m[i] = (a > 110 && r > 150 && r - b > 70) ? 1 : 0; }
  let x0 = W, y0 = H, x1 = 0, y1 = 0;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (m[y * W + x]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  const bw = x1 - x0 + 1, bh = y1 - y0 + 1, gh = rows * 2;
  const cov = (gx, gy) => {
    let s = 0, n = 0;
    for (let y = y0 + Math.floor(gy * bh / gh); y < y0 + Math.floor((gy + 1) * bh / gh); y++)
      for (let x = x0 + Math.floor(gx * bw / cols); x < x0 + Math.floor((gx + 1) * bw / cols); x++) { s += m[y * W + x]; n++; }
    return n ? s / n : 0;
  };
  const lines = [];
  for (let cy = 0; cy < rows; cy++) {
    let s = '';
    for (let cx = 0; cx < cols; cx++) { const a = cov(cx, cy * 2) >= threshold, b = cov(cx, cy * 2 + 1) >= threshold; s += a && b ? '█' : a ? '▀' : b ? '▄' : ' '; }
    lines.push(s.replace(/\s+$/, ''));
  }
  return lines;
}

(async () => {
  const out = { star: await star(13, 6, 0.2), word: wordmark('STARNET') };
  for (let r = 0; r < 6; r++) console.log((out.star[r] || '').padEnd(14) + out.word[r]);
  if (process.argv.includes('--write')) {
    const body = '/* bin/lib/logo.js — GENERATED by dev/cli-logo.cjs: the star cut from src-tauri/icon-source.png, the wordmark set in\n'
      + '   shadowed block letters leaning like the brand wordmark. Never edit by hand: regenerate. Six rows each. */\n'
      + "'use strict';\nmodule.exports = " + JSON.stringify(out, null, 1) + ';\n';
    fs.writeFileSync(path.join(REPO, 'bin', 'lib', 'logo.js'), body);
    console.log('wrote bin/lib/logo.js');
  }
})().catch(e => { console.error(e); process.exit(1); });
